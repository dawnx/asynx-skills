"""The Skill must agree with the service's exported contract.

``tests/fixtures/asynx-client-contract.json`` is generated by the Asynx backend
(``backend/scripts/export_client_contract.py``) from its own validator. These
tests read it instead of restating model names or error vocabulary, so a
service change shows up here as a failing test rather than as silent drift.
"""
from __future__ import annotations

import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parents[1] / "skills/asynx-image/scripts"))

from asxlib import errors, images
from asxlib.errors import _SERVICE_MESSAGES, AsxError, service_error_message

CONTRACT = json.loads(
    (Path(__file__).parent / "fixtures" / "asynx-client-contract.json").read_text(encoding="utf-8")
)
GENERIC = _SERVICE_MESSAGES["unsupported_image_parameters"]


class NoCatalogClient:
    base_url = "https://contract.test"
    cache_scope = "c" * 64

    def models(self):
        raise AssertionError("a canonical model name must not need the catalog")


def default_quality(model: str) -> str | None:
    body, _selected, _request_id = images.build_task(
        NoCatalogClient(), task_type="image.generate", model_selector=model,
        prompt="contract", image_size=None, aspect_ratio=None, quality=None,
        count=1, output_format="png", references=[],
    )
    return body["input"].get("quality")


class ServiceContractTests(unittest.TestCase):
    def test_quality_default_covers_exactly_the_service_gpt_image_25_26_names(self):
        for model in CONTRACT["gpt_image_25_26_models"]:
            with self.subTest(model=model):
                self.assertEqual(default_quality(model), "high")
        for model in CONTRACT["gpt_image_other_models"]:
            with self.subTest(model=model):
                self.assertIsNone(default_quality(model))

    def test_every_published_rejection_gets_a_specific_message(self):
        rejection = CONTRACT["unsupported_image_parameters"]
        for example in rejection["examples"]:
            with self.subTest(details=example["details"]):
                message = service_error_message(example["code"], details=example["details"])
                self.assertNotEqual(message, GENERIC)
                maximum = example["details"].get("maximum")
                if maximum is not None:
                    self.assertIn(str(maximum), message)
                for value in example["details"].get("allowed", []):
                    self.assertIn(value, message)

    def test_every_published_reason_and_option_field_is_understood(self):
        rejection = CONTRACT["unsupported_image_parameters"]
        for reason in rejection["reasons"]:
            with self.subTest(reason=reason):
                details = {"field": "input.extra", "reason": reason, "maximum": 3}
                self.assertNotEqual(service_error_message("unsupported_image_parameters", details=details), GENERIC)
        generic_option = service_error_message(
            "unsupported_image_parameters", details={"field": "input.extra", "reason": "unsupported_option"}
        )
        named = [
            field for field in rejection["fields"]
            if field.startswith(("input.extra.", "input.quality", "input.complexity", "input.moderation",
                                 "input.output_compression", "input.frame_", "input.svg", "input.safety_identifier"))
        ]
        self.assertTrue(named)
        for field in named:
            with self.subTest(field=field):
                message = service_error_message(
                    "unsupported_image_parameters", details={"field": field, "reason": "unsupported_option"}
                )
                self.assertNotEqual(message, generic_option)

    def test_published_allowed_values_are_shown_and_others_are_dropped(self):
        rejection = CONTRACT["unsupported_image_parameters"]
        sizes = [value for value in rejection["allowed_values"] if value.endswith("K")]
        message = service_error_message(
            "unsupported_image_parameters",
            details={"field": "input.image_size", "reason": "unsupported_size", "allowed": sizes},
        )
        for size in sizes:
            self.assertIn(size, message)
        unsafe = service_error_message(
            "unsupported_image_parameters",
            details={"field": "input.image_size", "reason": "unsupported_size", "allowed": ["private-upstream"]},
        )
        self.assertNotIn("private-upstream", unsafe)

    def test_submission_rejection_table_matches_the_service(self):
        # A code missing here is replayed forever; a code wrongly listed here drops a paid task.
        submission = CONTRACT["task_submission"]
        self.assertEqual(errors.REJECTED_5XX_CODES, frozenset(submission["rejected_5xx_codes"]))
        self.assertEqual(errors.REQUEST_403_CODES, frozenset(submission["request_403_codes"]))
        self.assertEqual(errors.UNCONFIRMED_4XX_STATUSES, frozenset(submission["unconfirmed_4xx_statuses"]))
        for code, statuses in submission["user_facing_errors"].items():
            for status in statuses:
                with self.subTest(code=code, status=status):
                    outcome = AsxError("", code=code, http_status=status).submission_outcome
                    if status >= 500:
                        self.assertEqual(outcome, "later" if code in submission["rejected_5xx_codes"] else None)
                    else:
                        self.assertIsNotNone(outcome)

    def test_every_user_facing_service_error_has_its_own_message(self):
        # Otherwise the user reads "no reason provided" for a spending limit or an expired file.
        for code, statuses in CONTRACT["task_submission"]["user_facing_errors"].items():
            for status in statuses:
                with self.subTest(code=code, status=status):
                    self.assertNotEqual(
                        service_error_message(code, http_status=status),
                        service_error_message("code-the-client-does-not-know", http_status=status),
                    )

    def test_guide_fields_and_statuses_match_the_client_parser(self):
        guide = CONTRACT["model_guide"]
        self.assertEqual(guide["fields"], ["content", "model", "revision", "status"])
        self.assertEqual(guide["statuses"], ["documented", "unconfirmed"])
        self.assertEqual(guide["path"], "/v1/tasks/models/{model}/guide")


if __name__ == "__main__":
    unittest.main()
