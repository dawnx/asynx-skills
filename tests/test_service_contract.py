"""The Skill must agree with the service's exported contract.

``tests/fixtures/asynx-client-contract.json`` is generated by the Asynx backend
(``backend/scripts/export_client_contract.py``). Error meanings and wording
arrive with each response and default models are chosen by the service, so the
contract only pins what the Skill has to hard-code: the vocabulary it acts on.
"""
from __future__ import annotations

import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parents[1] / "skills/asynx-image/scripts"))

from asxlib import errors

CONTRACT = json.loads(
    (Path(__file__).parent / "fixtures" / "asynx-client-contract.json").read_text(encoding="utf-8")
)


class ServiceContractTests(unittest.TestCase):
    def test_next_steps_the_skill_acts_on_are_the_ones_the_service_sends(self):
        # A step the Skill does not know is treated as "retry later"; a batch would
        # then keep retrying an account problem instead of pausing.
        guidance = CONTRACT["error_guidance"]
        self.assertEqual(list(errors.NEXT_STEPS), guidance["next_steps"])
        self.assertLess(errors.PAUSING_STEPS, set(guidance["next_steps"]))

    def test_guide_fields_and_statuses_match_the_client_parser(self):
        guide = CONTRACT["model_guide"]
        self.assertEqual(guide["fields"], ["content", "model", "revision", "status"])
        self.assertEqual(guide["statuses"], ["documented", "unconfirmed"])
        self.assertEqual(guide["path"], "/v1/tasks/models/{model}/guide")


if __name__ == "__main__":
    unittest.main()
